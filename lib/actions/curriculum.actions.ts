'use server';

import Groq from 'groq-sdk';
import { createSupabaseClient } from '../supabase';
import { auth } from '@clerk/nextjs/server';

const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

export interface ModuleTemplate {
  order: number;
  name: string;
  topic: string;
  duration: number;
}

export async function generateSyllabus(targetSkill: string): Promise<ModuleTemplate[]> {
  const prompt = `You are an expert technical curriculum designer. The user wants to learn: "${targetSkill}".
  
  Generate a highly focused, modern learning path. Strip away all outdated theoretical filler and focus only on industry-standard practices. 
  Break the learning path into 3 to 5 sequential modules.
  
  You MUST return the output ONLY as a valid JSON object containing a single key called "modules", which holds an array of objects. Do not include any conversational text.
  
  Required JSON schema:
  {
    "modules": [
      {
        "order": 1,
        "name": "Module Title",
        "topic": "Specific technical concepts covered in this module",
        "duration": 15
      }
    ]
  }`;

  try {
    const chatCompletion = await groq.chat.completions.create({
      model: 'openai/gpt-oss-120b', 
      messages: [{ role: 'user', content: prompt }],
      temperature: 0.2, 
      response_format: { type: "json_object" }, 
    });

    const content = chatCompletion.choices[0]?.message?.content;
    if (!content) throw new Error("No content generated by Groq");

    const parsed = JSON.parse(content);
    return parsed.modules;

  } catch (error: any) {
    console.error("Groq API Error Details:", error);
    throw new Error(`Failed to map curriculum: ${error.message}`);
  }
}

export const createLearningPath = async (targetSkill: string, userInterest: string) => {
    const { userId } = await auth();
    if (!userId) throw new Error("Unauthorized");

    const supabase = createSupabaseClient();
    const generatedModules = await generateSyllabus(targetSkill);

    const { data: pathData, error: pathError } = await supabase
        .from('learning_paths')
        .insert({ 
            user_id: userId, 
            target_skill: targetSkill,
            user_interest: userInterest || 'general real-world applications' // Fallback
        })
        .select()
        .single();

    if (pathError || !pathData) throw new Error(pathError?.message || 'Failed to create path');

    const modulesToInsert = generatedModules.map((mod) => ({
        path_id: pathData.id,
        module_order: mod.order,
        name: mod.name,
        topic: mod.topic,
        duration: mod.duration,
        is_completed: false
    }));

    const { error: modulesError } = await supabase.from('path_modules').insert(modulesToInsert);
    if (modulesError) throw new Error(modulesError.message);

    return true;
}

export const getActiveLearningPath = async () => {
    const { userId } = await auth();
    if (!userId) return null;

    const supabase = createSupabaseClient();

    // 1. Fetch the most recent learning path for the user
    const { data: pathData, error: pathError } = await supabase
        .from('learning_paths')
        .select('*')
        .eq('user_id', userId)
        .order('created_at', { ascending: false })
        .limit(1)
        .single();

    // If no path exists yet, just return null
    if (pathError || !pathData) return null;

    // 2. Fetch all modules for this specific path
    const { data: modulesData, error: modulesError } = await supabase
        .from('path_modules')
        .select('*')
        .eq('path_id', pathData.id)
        .order('module_order', { ascending: true });

    if (modulesError) throw new Error(modulesError.message);

    return { 
        path: pathData, 
        modules: modulesData 
    };
}

export const getPathModule = async (moduleId: string) => {
    const supabase = createSupabaseClient();
    
    // Use Supabase foreign key joining to grab the parent path's interest
    const { data, error } = await supabase
        .from('path_modules')
        .select(`
            *,
            learning_paths ( user_interest )
        `)
        .eq('id', moduleId)
        .single();

    if (error || !data) throw new Error(error?.message || 'Module not found');
    
    return data;
}

export const markModuleCompleted = async (moduleId: string) => {
    const supabase = createSupabaseClient();
    
    const { error } = await supabase
        .from('path_modules')
        .update({ is_completed: true })
        .eq('id', moduleId);

    if (error) throw new Error(error.message);
    
    return true;
}